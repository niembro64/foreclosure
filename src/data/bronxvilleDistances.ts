const NEW_JERSEY_COUNTY_DISTANCES: Record<string, number> = {
  essex: 24.3,
  hudson: 19.5,
  passaic: 25.6,
  union: 31.8,
};

export type DistanceEstimate = {
  miles: number;
  basis: 'town' | 'ZIP' | 'county';
};

export const getConnecticutDistance = (town: string): DistanceEstimate | null => {
  const miles = CONNECTICUT_TOWN_DISTANCES[town.trim().toLowerCase()];
  return miles === undefined ? null : { miles, basis: 'town' };
};

export const getNewJerseyDistance = (address: string, county: string): DistanceEstimate | null => {
  const zip = address.match(/\b(0[789]\d{3})\b/)?.[1];
  const zipMiles = zip ? NEW_JERSEY_ZIP_DISTANCES[zip] : undefined;
  if (zipMiles !== undefined) return { miles: zipMiles, basis: 'ZIP' };

  const countyMiles = NEW_JERSEY_COUNTY_DISTANCES[county.trim().toLowerCase()];
  return countyMiles === undefined ? null : { miles: countyMiles, basis: 'county' };
};
